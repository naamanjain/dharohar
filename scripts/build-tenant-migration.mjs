// Build the migration-runner copy of the tenant migration from the drill copy.
//
// server/src/db-draft/0004_*.sql is written for `psql -f` (it uses \set and its own BEGIN/COMMIT so
// the drill can run it standalone and see NOTICE output). The runner cannot execute psql
// meta-commands, and it already wraps every file in a transaction — a nested BEGIN would commit the
// runner's transaction early, which is exactly the kind of subtle difference that makes two copies
// of a migration drift. So the integrated file is DERIVED here, and the two are compared, instead of
// one of them being retyped by hand and hoped to match.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = 'C:/Users/allin/OneDrive/Desktop/AI/DHAROHAR';
const DRAFT = path.join(ROOT, 'server/src/db-draft/0004_canonical_districts_and_tenants.sql');
const OUT = path.join(ROOT, 'server/src/db/migrations/0004_canonical_districts_and_tenants.sql');

const source = fs.readFileSync(DRAFT, 'utf8');
const lines = source.split(/\r?\n/);

const dropped = [];
const kept = lines.filter((line) => {
  const t = line.trim();
  // psql-only meta-commands
  if (/^\\\w+/.test(t)) { dropped.push(t); return false; }
  // the runner opens and closes the transaction; the file must not
  if (/^(BEGIN|COMMIT);$/i.test(t)) { dropped.push(t); return false; }
  return true;
});

const header = [
  '-- Runner copy of server/src/db-draft/0004_canonical_districts_and_tenants.sql.',
  '-- Generated by scripts/build-tenant-migration.mjs; edit the draft and regenerate, do not hand-edit',
  '-- both. Differences from the draft: psql meta-commands removed, and BEGIN/COMMIT removed because',
  '-- the migration runner applies every file inside its own transaction (and records the result in',
  '-- schema_migrations). Semantics are otherwise identical.',
  '',
];

fs.writeFileSync(OUT, header.concat(kept).join('\n'));

const removedCode = dropped.filter((d) => !/^--/.test(d));
console.log(`wrote ${OUT}`);
console.log(`statements removed for runner compatibility: ${removedCode.length} -> ${removedCode.join(' | ')}`);
console.log(`lines: draft=${lines.length} integrated=${kept.length + header.length}`);
